"""M77：把去重后的独立根因 P0 导出为 GitHub Security Advisory 草稿。

一条根因一份 Markdown（绝不按 219 条继承路由生成 219 份重复草稿）：

    python cli.py scan <repo> --auto --offline --fix --advisory-dir advisories/

每份包含：
  · GHSA 占位编号 + Affected Component & File:Line
  · Vulnerability Mechanism & CWE（从 CATEGORIES 单一事实源取）
  · Taint Flow Mermaid（build_taint_graph；无图时给出降级说明）
  · PoC Harness（PocSynthesizer；自检通过才贴代码）
  · Verified Patch Diff（从 --fix 报告按类目切分；没有则标注需人工）
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

from core.agents.vuln_categories import CATEGORIES
from core.context.cvss import compute_cvss31
from core.context.taint_graph import build_taint_graph
from core.sandbox.poc_synthesizer import PocSynthesizer


def _ghsa_id(signature: str) -> str:
    h = hashlib.sha256(signature.encode()).hexdigest().upper()
    return f"GHSA-{h[0:4]}-{h[4:8]}-{h[8:12]}"


def _slug(s: str) -> str:
    s = re.sub(r"[^0-9A-Za-z]+", "-", s or "finding").strip("-").lower()
    return (s or "finding")[:48]


def _split_fix_sections(text: str) -> dict[str, str]:
    """从 --fix 报告里按 `## [类目]` 切出 diff 块。"""
    out: dict[str, str] = {}
    cur = None
    buf: list[str] = []
    for line in (text or "").splitlines():
        m = re.match(r"^## \[([\w-]+)\]", line)
        if m:
            if cur and buf:
                out[cur] = "\n".join(buf).strip()
            cur, buf = m.group(1).lower().replace("-", "_"), []
        elif cur is not None:
            buf.append(line)
    if cur and buf:
        out[cur] = "\n".join(buf).strip()
    return out


def _rel(path: str, repo: Path) -> str:
    try:
        return Path(path).resolve().relative_to(repo.resolve()).as_posix()
    except ValueError:
        return Path(path).as_posix()


def _fallback_flow(rc: dict) -> str:
    cat = rc["category"]
    return ("```mermaid\nflowchart LR\n"
            f'  R["{"全局配置" if rc["kind"] == "global-config" else "入口"}'
            f' {rc["unit_name"]}"]\n'
            f'  S["Sink: {cat}"]\n'
            "  R --> S\n```")


def export_advisories(root_causes: list[dict], repo: Path,
                      out_dir: Path, fix_text: str = "") -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    diffs = _split_fix_sections(fix_text)
    synth = PocSynthesizer()
    written: list[Path] = []
    for rc in root_causes:
        cat = rc["category"]
        rep = rc["representative"]
        cwe = CATEGORIES[cat].cwe if cat in CATEGORIES else "CWE-000"
        cvss = compute_cvss31(cat, rc["unit_name"],
                              rc["kind"] == "global-config")
        rel = _rel(rc["file"], repo)
        comp = Path(rc["file"]).name
        graph = build_taint_graph(rep, cat) or _fallback_flow(rc)
        poc = synth.synthesize(rep, cat)
        if poc.self_check_ok:
            lang = poc.language
            poc_block = f"```{lang}\n{poc.content}\n```"
            poc_note = f"自检：{poc.self_check_msg}"
        else:
            poc_block = f"（PoC 合成自检未通过：{poc.self_check_msg}）"
            poc_note = "需手工补全"
        patch = diffs.get(cat)
        if not patch:
            patch = ("（本次未跑 `--fix` 或该类目没有确定性补丁器；"
                     "架构/配置类缺陷按建议手工修复。）")
        routes = "\n".join(f"- `{x}`" for x in rc["routes"]) or "- （无）"
        # M111：一键复现命令单。三件事必须齐：仓库相对路径、单元名、类目 ——
        # 只看 `python cli.py scan <repo> --auto` 无法定位到这一条，读者还得
        # 自己在 65 份草稿里找。命令直接贴能跑的那种。
        # M111：一键复现命令单。命令必须是**现在就能跑**的形态 —— 写一条
        # 不存在的 `--unit` 出来，读者复制粘贴只会得到 argparse 报错，
        # 那比没有这节更糟。定位靠"仓库 + 文件:行"，命令本身只做全仓复核。
        repro = (
            f"# 1) 离线复核本仓（本根因在输出里按 "
            f"{rel}:{rc['line']} 定位）\n"
            f"python cli.py scan {repo} --auto --offline\n\n"
            f"# 2) 生成 PoC + 自检补丁 + 披露包\n"
            f"python cli.py scan {repo} --auto --offline "
            f"--emit-poc poc/ --fix --advisory-dir adv/\n\n"
            f"# 3) 只看本类目（24 类中的 {cat}）\n"
            f"python cli.py scan {repo} --categories {cat} --offline")
        # M111：补丁可用性徽章 —— 只有**真的**有通过自检的 diff 才打标。
        fix_badge = ("**[Auto-Fix Verified]**" if patch
                     and "```diff" in patch else "")
        body = f"""# {cwe} · {cat} in {comp} {fix_badge}

**{_ghsa_id(rc["signature"])}** ｜ 规则层 P0 ｜ {rc["kind"]}
**CVSS v3.1：{cvss["score"]:.1f} {cvss["severity"]}** ｜ `{cvss["vector"]}`

## Affected Component

- Repository: `{repo}`
- File: `{rel}:{rc["line"]}`
- Representative entry: `{rc["unit_name"]}`
- Affected routes: **{rc["affected_routes"]}**（同一独立根因）

{routes}

## Vulnerability Mechanism

类目 `{cat}`（{cwe}）。根因签名：`{rc["signature"]}`。

- `global-config`：结论来自 `框架装配证据` 中的同一份全局配置，所有
  受影响路由共享该根因；修一处配置即消解整组告警。
- `file-level`：密钥/凭证直接写在配置文件或工具类中。
- `endpoint`：入口方法自身的确定性证据，按文件/行独立。

## Taint Flow

{graph}

## PoC Harness

{poc_block}

> {poc_note}

## Verified Patch

{patch}

## Quick Reproduction Command

```bash
{repro}
```

## References

- CWE: https://cwe.mitre.org/data/definitions/{cwe.split("-")[-1]}.html
- Generated by nexus-audit `scan --auto --advisory-dir`
"""
        name = (f"{_ghsa_id(rc['signature'])}-{_slug(cat)}-"
                f"{_slug(rc['unit_name'])}.md")
        p = out_dir / name
        p.write_text(body, encoding="utf-8")
        written.append(p)
    if written:
        _write_index(out_dir, written)
    return written


_INDEX_ROW_RE = re.compile(
    r"^\*\*CVSS v3\.1：([\d.]+) (\w+)\*\*", re.M)
_INDEX_TITLE_RE = re.compile(r"^# .*$", re.M)


def _write_index(out_dir: Path, paths: list[Path]) -> None:
    """M111：跨仓库披露总目录 `INDEX.md`，按 CVSS 降序。

    每份草稿的标题行 + CVSS 行是**唯一事实源** —— 索引从草稿正文里读，
    不重新算一遍分数（重算就会与正文漂移，两份数字打架时没人知道信哪个）。
    """
    rows: list[tuple[float, str, str, str, str]] = []
    for p in paths:
        try:
            txt = p.read_text(encoding="utf-8")
        except OSError:
            continue
        m = _INDEX_ROW_RE.search(txt)
        if not m:
            continue
        score, sev = float(m.group(1)), m.group(2)
        t = _INDEX_TITLE_RE.search(txt)
        title = (t.group(0)[2:].strip() if t else p.stem)
        cwe = title.split("·")[0].strip() if "·" in title else ""
        cat = (title.split("·")[1].strip().split()[0] if "·" in title else "")
        rows.append((score, sev, cwe, cat, p.name))
    rows.sort(key=lambda r: (-r[0], r[4]))
    lines = [
        "# 披露草稿总目录（nexus-audit `--advisory-dir`）",
        "",
        f"共 **{len(rows)}** 份 GHSA 草稿，按 CVSS v3.1 分值降序。",
        "带 [Auto-Fix Verified] 的草稿内嵌通过自检的补丁 diff。",
        "",
        "| CVSS | 严重级 | CWE | 类目 | 草稿 |",
        "|---|---|---|---|---|",
    ]
    for score, sev, cwe, cat, name in rows:
        badge = ""
        try:
            if "Auto-Fix Verified" in (out_dir / name).read_text(
                    encoding="utf-8"):
                badge = " 🔧"
        except OSError:
            pass
        lines.append(f"| {score:.1f} | {sev} | {cwe} | {cat} | "
                     f"[{name}]({name}){badge} |")
    (out_dir / "INDEX.md").write_text("\n".join(lines) + "\n",
                                      encoding="utf-8")
